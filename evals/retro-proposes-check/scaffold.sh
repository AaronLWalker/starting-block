"""Generate docs/api.md from src/routes.py.  build: write it.  check: exit 1 if it's stale."""
import sys
from pathlib import Path

sys.path.insert(0, "src")
from routes import ROUTES

OUT = Path("docs/api.md")


def render():
    rows = ["| Method | Path | What |", "|---|---|---|"]
    rows += ["| {} | `{}` | {} |".format(m, p, w) for m, p, w in ROUTES]
    return "# API\n\nGenerated by `scripts/gen_api.py`; edit `src/routes.py`.\n\n" + "\n".join(rows) + "\n"


if __name__ == "__main__":
    if sys.argv[1:] == ["build"]:
        OUT.write_text(render())
    elif sys.argv[1:] == ["check"]:
        if OUT.read_text() != render():
            sys.exit("docs/api.md is stale: run python3 scripts/gen_api.py build")
    else:
        sys.exit("usage: gen_api.py build|check")
EOF
python3 scripts/gen_api.py build
